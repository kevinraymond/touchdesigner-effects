def code(ch):
    """The glyph code of one character (GLSL side uses the same numbers)."""
    return ORDER.index(ch)


def codes(text):
    return [code(c) for c in text]


def font_glsl():
    rows = []
    for ch in ORDER:
        for r in GLYPHS[ch].split():
            assert len(r) == 5, (ch, r)
            rows.append(int(r.replace('#', '1').replace('.', '0'), 2))
    body = ','.join(str(v) for v in rows)
    return ('// 5x7 bitmap font drawn for touchdesigner-effects (dev/protos/blob/font5x7.py).\n'
            'const int FONT[{n}] = int[{n}]({body});\n').format(n=len(rows), body=body)
